"""Runs the full test suite with coverage and writes docs/TEST_RESULTS.md.

    python scripts/generate_test_report.py
"""
from __future__ import annotations

import platform
import re
import subprocess
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "TEST_RESULTS.md"

SCENARIOS = [
    ("Happy path (3 workflows, all branches, manual review)", "test_happy_path.py"),
    ("Invalid input", "test_invalid_input.py"),
    ("Duplicate requests / idempotency (incl. 8 concurrent threads)", "test_idempotency.py"),
    ("Dependency failure (outage, timeout, fail-safe, circuit breaker, backoff)", "test_dependency_failure.py"),
    ("Retry flow (RETRY_PENDING -> retry -> decision, retry budget)", "test_retry_flow.py"),
    ("Rule change via configuration (threshold, new rule, new stage, versioning)", "test_rule_change.py"),
    ("Partial save failure (rollback + recovery)", "test_persistence_failure.py"),
    ("Auditability & explainability", "test_audit_explain.py"),
    ("Rule engine (condition DSL) unit tests", "test_conditions.py"),
    ("CLI interface", "test_cli.py"),
]


def main() -> int:
    cmd = [sys.executable, "-m", "pytest", "-p", "no:cacheprovider", "-v", "-o", "addopts=",
           "--cov=app", "--cov-report=term"]
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    output = proc.stdout.replace(str(ROOT) + "\\", "").replace(str(ROOT) + "/", "")

    results = re.findall(r"^(tests[\\/](\S+?\.py))::(\S+) (PASSED|FAILED|ERROR|SKIPPED)", output, re.M)
    per_file: Counter = Counter()
    passed_per_file: Counter = Counter()
    for _, fname, _, status in results:
        per_file[fname] += 1
        passed_per_file[fname] += status == "PASSED"
    summary = re.search(r"=+ (.*(?:passed|failed).*) =+\s*$", output, re.M)
    total_cov = re.search(r"^TOTAL\s+\d+\s+\d+\s+(\d+%)", output, re.M)
    cov_block = re.search(r"(Name\s+Stmts.*?^TOTAL.*?$)", output, re.S | re.M)

    lines = [
        "# Test Results\n",
        f"_Generated by `python scripts/generate_test_report.py` on "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')} (Python {platform.python_version()}, {platform.system()})._\n",
        f"**Result: {summary.group(1) if summary else 'see output'}** | "
        f"**Code coverage: {total_cov.group(1) if total_cov else 'n/a'}**\n",
        "## Coverage of required scenarios\n",
        "| Scenario | Test file | Tests | Passed |",
        "|---|---|---|---|",
    ]
    for label, fname in SCENARIOS:
        lines.append(f"| {label} | `tests/{fname}` | {per_file[fname]} | {passed_per_file[fname]} |")
    lines.append(f"| **Total** | | **{sum(per_file.values())}** | **{sum(passed_per_file.values())}** |\n")

    lines.append("## Every test\n")
    lines.append("| # | File | Test | Result |\n|---|---|---|---|")
    for i, (_, fname, test, status) in enumerate(results, 1):
        icon = "PASS" if status == "PASSED" else status
        lines.append(f"| {i} | `{fname}` | `{test}` | {icon} |")

    if cov_block:
        lines.append("\n## Code coverage by module\n")
        lines.append("```\n" + cov_block.group(1) + "\n```")
        lines.append("\nThe remaining uncovered lines are mainly defensive error paths (e.g. storage completely "
                     "unavailable while recording an error) and admin/demo endpoints.\n")

    lines.append("## How to reproduce\n\n```bash\npip install -r requirements.txt\npytest                 "
                 "# quick run\npython scripts/generate_test_report.py   # regenerate this report\n```\n")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} -> {summary.group(1) if summary else '?'}, coverage {total_cov.group(1) if total_cov else '?'}")
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
